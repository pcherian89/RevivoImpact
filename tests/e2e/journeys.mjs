// Plays journeys A, B, C (step 1) and E with real clicks ("I'll do it"), checking that each action shows up for the other side.
import { createRequire } from "node:module";
import { resolve } from "node:path";
const { chromium } = createRequire(import.meta.url)("playwright");
const file = "file://" + resolve(process.env.DIST ?? "dist/index.html");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push(String(e)));
let ok = 0, bad = 0;
const check = async (label, cond) => {
  if (cond) ok++;
  else { bad++; console.log("FAIL:", label); }
};
const go = async (path) => { await page.evaluate((p) => (location.hash = p), "/" + path); await page.waitForTimeout(80); };
const text = () => page.evaluate(() => document.body.innerText);
const click = async (name, opts = {}) => { await page.getByRole("button", { name, exact: false, ...opts }).first().click(); await page.waitForTimeout(60); };

// ---- Journey A at 12 Apr
await page.goto(`${file}?moment=apr12&motion=reduced#/app/ingrid/opps`);
await page.waitForTimeout(200);
await click(/^Publish$/);
await check("A1 Ingrid publishes (four-eyes)", (await text()).includes("Published opportunity (four-eyes)"));
await go("app/daniel/opps");
await check("A1 the drafter sees it open", !(await text()).includes("Awaiting approval"));
await go("join");
await page.getByLabel("An athlete (18 or over)").check();
await click("Create my account");
await check("A2 Amira registered and lands on her profile", (await text()).includes("What do funders see about me?"));
await click("Add my results, coach and support");
await click("Ask my federation to confirm");
await check("A3 profile built and confirmation asked", (await text()).includes("Confirmation asked of Ardent Judo Federation"));
await go("app/amira/discover");
const disc = await text();
await check("A4 five open opportunities from five organisations", /5 open on .* from 5 organisations/.test(disc));
await check("A4 two shown not eligible", (disc.match(/Not eligible/g) || []).length >= 2);
await page.getByRole("tab", { name: /Sponsors & funders/ }).click();
await check("A4 seven relevant sponsors", (await page.getByRole("tab", { name: /Sponsors & funders/ }).innerText()).includes("7"));
await go("app/amira/opportunity/eas");
await check("A5 eligibility 4 met · 1 to check · 1 to add", (await text()).includes("4 of 6 met · 1 for the panel to check · 1 to add"));
await go("app/amira/apply/eas");
await click("Help me organise this");
await page.getByLabel("Amount requested (USD)").fill("4800");
await click("Submit application");
await check("A6 an unedited AI draft cannot be submitted", (await text()).includes("statement in your own words"));
await page.getByLabel("Statement").fill("I compete in judo at national U21 level and train at Saltmere Sports Academy. My family cannot cover coaching fees and travel this season.");
await page.locator("#other").fill("None");
await click("Submit application");
await check("A6–A7 submitted", (await text()).includes("Submitted · in review"));
await go("app/daniel/apps");
await check("A7 Daniel sees Amira's application in the pipeline", (await text()).includes("Amira Haddad"));

