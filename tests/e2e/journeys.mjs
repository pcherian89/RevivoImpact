// Plays journeys A, B, C (step 1) and E with real clicks ("I'll do it"), checking that each action shows up for the other side.
import { createRequire } from "node:module";
import { resolve } from "node:path";
const { chromium } = createRequire(import.meta.url)("playwright");
const file = "file://" + resolve(process.env.DIST ?? "dist/index.html");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push(String(e)));
let ok = 0, bad = 0;
const check = async (label, cond) => {
  if (cond) ok++;
  else { bad++; console.log("FAIL:", label); }
};
const go = async (path) => { await page.evaluate((p) => (location.hash = p), "/" + path); await page.waitForTimeout(80); };
const text = () => page.evaluate(() => document.body.innerText);
/** Was this action written to the audit? (The platform audit lists every action; the screen keeps its place.) */
const audited = async (action) => {
  const back = await page.evaluate(() => location.hash);
  await go("app/alex/admin");
  await page.getByRole("tab", { name: /Audit/ }).click();
  const found = (await text()).includes(action);
  await page.evaluate((h) => (location.hash = h), back);
  await page.waitForTimeout(80);
  return found;
};
const click = async (name, opts = {}) => { await page.getByRole("button", { name, exact: false, ...opts }).first().click(); await page.waitForTimeout(60); };
// The offer reason starts empty (the funder's own words); tests take the one-tap suggestion when the box is empty.
const suggestReason = async () => {
  const b = page.getByRole("button", { name: "Use a suggested reason, then edit it" });
  if (await b.count()) await b.first().click();
};

